-- مزامنة: المقرر الدراسي يأخذ مادته من اسمها إن لم تُحدد (ملفات البيانات القديمة تكتب subject نصًا)،
-- ويبقى نص subject مطابقًا لاسم المادة دائمًا.
create or replace function public._courses_subject_sync() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if new.kind = 'course' then
    if new.subject_id is null then select s.id into new.subject_id from public.subjects s where s.name = new.subject; end if;
    if new.subject_id is not null then new.subject := coalesce((select s.name from public.subjects s where s.id = new.subject_id), new.subject); end if;
  end if;
  return new;
end $$;
drop trigger if exists courses_subject_sync on public.courses;
create trigger courses_subject_sync before insert or update of subject, subject_id, kind on public.courses
  for each row execute function public._courses_subject_sync();

-- مقرر واحد لكل (مادة، صف، فصل دراسي)؛ يُنشأ الفهرس فقط إن لم تكن في البيانات الحالية خانة مكررة
do $$ begin
  if not exists (select 1 from pg_indexes where schemaname = 'public' and indexname = 'courses_subject_slot_key')
     and not exists (select 1 from public.courses where kind = 'course' and subject_id is not null
                     group by subject_id, grade, term having count(*) > 1) then
    create unique index courses_subject_slot_key on public.courses (subject_id, grade, term) where kind = 'course' and subject_id is not null;
  end if;
end $$;

-- معرّفات المقررات الجديدة تُولَّد تلقائيًا بدءًا من 101 (1–100 محجوزة للمقررات التي تُضاف بملفات البيانات في المستودع)
do $$
declare v_seq text; v_max bigint; v_last bigint;
begin
  if (select attidentity from pg_attribute where attrelid = 'public.courses'::regclass and attname = 'id') = '' then
    alter table public.courses alter column id add generated by default as identity;
  end if;
  v_seq := pg_get_serial_sequence('public.courses', 'id');
  select greatest(coalesce(max(id), 0), 100) into v_max from public.courses;
  execute format('select last_value from %s', v_seq) into v_last;
  if v_last < v_max then perform setval(v_seq, v_max, true); end if;
end $$;

-- هل المقرر ظاهر لغير المالك؟ المقرر «قيد الإعداد» في مادة ليس فيها مقرر متاح بعد لا يظهر إلا للمالك
-- (فلا تظهر مادة جديدة للفريق قبل جاهزيتها). المقررات بلا مادة (التحصيلي) كما كانت.
create or replace function public._course_listed(p_course bigint) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select public.is_admin() or exists (select 1 from public.courses c where c.id = p_course and (c.status = 'ready' or c.subject_id is null
    or exists (select 1 from public.courses r where r.subject_id = c.subject_id and r.status = 'ready')))
$$;

-- المقررات في الصفحة الأولى ومبدّل المقرر: أُضيفت مادة كل مقرر (subjectId) وعدد معلميه (للمالك)، والأعداد بتجميع واحد لكل جدول
create or replace function public.get_courses() returns jsonb
language plpgsql stable security definer set search_path = public, pg_temp as $$
declare v_admin boolean := public.is_admin();
begin
  perform public._require_member();
  return (with vis as (select c.* from courses c where public._course_ok(c.id) and public._course_listed(c.id)),
    chs as (select ch.course_id, count(*) n from chapters ch join vis on vis.id = ch.course_id group by 1),
    obs as (select ch.course_id, count(*) n from objectives o join lessons l on l.id = o.lesson_id join chapters ch on ch.id = l.chapter_id
            join vis on vis.id = ch.course_id group by 1),
    qs as (select ch.course_id, count(*) n, count(*) filter (where q.status = 'approved') a
           from questions q join objectives o on o.id = q.objective_id join lessons l on l.id = o.lesson_id join chapters ch on ch.id = l.chapter_id
           join vis on vis.id = ch.course_id where not q.excluded group by 1),
    sts as (select e.course_id, count(*) n from course_enrollments e join profiles p on p.user_id = e.user_id and p.role = 'student'
            join vis on vis.id = e.course_id where public._visible_student(e.user_id) group by 1),
    tcs as (select t.course_id, count(*) n from teacher_courses t join profiles p on p.user_id = t.teacher_id and p.role = 'viewer'
            join vis on vis.id = t.course_id where v_admin group by 1)
    select coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'code', c.code, 'title', c.title, 'grade', c.grade, 'term', c.term,
      'status', c.status, 'eta', c.eta, 'sortOrder', c.sort_order, 'kind', c.kind, 'subjectId', c.subject_id,
      'chapters', coalesce(chs.n, 0), 'objectives', coalesce(obs.n, 0), 'questions', coalesce(qs.n, 0), 'approved', coalesce(qs.a, 0),
      'students', coalesce(sts.n, 0), 'teachers', case when v_admin then coalesce(tcs.n, 0) end)
      order by c.sort_order, c.id), '[]')
    from vis c left join chs on chs.course_id = c.id left join obs on obs.course_id = c.id left join qs on qs.course_id = c.id
      left join sts on sts.course_id = c.id left join tcs on tcs.course_id = c.id);
end $$;

-- المواد مع أرقامها. المالك يرى كل المواد (حتى التي بلا مقررات)؛ غيره يرى مواد المقررات المتاحة التي يصل إليها فقط
-- (المعلم: مقرراته المسندة الجاهزة؛ الطالب: مقرراته المسندة الجاهزة).
create or replace function public.get_subjects() returns jsonb
language plpgsql stable security definer set search_path = public, pg_temp as $$
declare v_role text := public.my_role(); v_admin boolean := public.my_role() = 'admin'; v_student boolean := public.my_role() = 'student';
begin
  if auth.uid() is null then raise exception 'يلزم تسجيل الدخول' using errcode = '28000'; end if;
  if v_role is null or v_role = 'pending' then raise exception 'حسابك بانتظار التفعيل من المشرف' using errcode = '42501'; end if;
  return (with vis as (
      select c.id, c.subject_id, c.status from courses c
      where c.kind = 'course' and c.subject_id is not null
        and (v_admin or (c.status = 'ready' and case when v_student
              then exists (select 1 from course_enrollments e where e.user_id = auth.uid() and e.course_id = c.id)
              else public._course_ok(c.id) end))),
    qs as (select vis.subject_id, count(*) n, count(*) filter (where q.status = 'approved') a
           from questions q join objectives o on o.id = q.objective_id join lessons l on l.id = o.lesson_id join chapters ch on ch.id = l.chapter_id
           join vis on vis.id = ch.course_id where not q.excluded group by 1),
    sts as (select vis.subject_id, count(distinct e.user_id) n from course_enrollments e join profiles p on p.user_id = e.user_id and p.role = 'student'
            join vis on vis.id = e.course_id where not v_student and public._visible_student(e.user_id) group by 1),
    tcs as (select vis.subject_id, count(distinct t.teacher_id) n from teacher_courses t join profiles p on p.user_id = t.teacher_id and p.role = 'viewer'
            join vis on vis.id = t.course_id where not v_student group by 1),
    cs as (select subject_id, count(*) n, count(*) filter (where status = 'ready') r from vis group by 1)
    select coalesce(jsonb_agg(jsonb_build_object('id', s.id, 'name', s.name, 'icon', s.icon, 'color', s.color, 'sort', s.sort_order,
        'courses', coalesce(cs.n, 0), 'ready', coalesce(cs.r, 0), 'questions', coalesce(qs.n, 0), 'approved', coalesce(qs.a, 0),
        'students', case when v_student then null else coalesce(sts.n, 0) end, 'teachers', case when v_student then null else coalesce(tcs.n, 0) end)
        order by s.sort_order, s.name), '[]')
    from subjects s left join cs on cs.subject_id = s.id left join qs on qs.subject_id = s.id
      left join sts on sts.subject_id = s.id left join tcs on tcs.subject_id = s.id
    where v_admin or cs.n > 0);
end $$;

-- ---------- إدارة المواد والمقررات (لمالك المشروع) ----------
-- إضافة مادة أو تعديلها: p = {mode: 'create'|'update', id, name, icon, color, sort}
create or replace function public.admin_save_subject(p jsonb) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_mode text := coalesce(p->>'mode', 'create');
  v_id text := lower(trim(coalesce(p->>'id', '')));
  v_name text := regexp_replace(trim(coalesce(p->>'name', '')), '\s+', ' ', 'g');
  v_icon text := trim(coalesce(p->>'icon', ''));
  v_color text := trim(coalesce(p->>'color', ''));
  v_sort int;
  v_before jsonb; v_after jsonb;
begin
  perform public._require_admin();
  if v_mode not in ('create', 'update') then raise exception 'إجراء غير صالح' using errcode = '22023'; end if;
  if v_id !~ '^[a-z][a-z0-9-]{1,30}$' then raise exception 'رمز المادة: حروف إنجليزية صغيرة وأرقام وشرطة (2–31 حرفًا) يبدأ بحرف، مثل phys' using errcode = '22023'; end if;
  if char_length(v_name) not between 2 and 40 then raise exception 'اسم المادة بين 2 و40 حرفًا' using errcode = '22023'; end if;
  if v_icon not in ('flask', 'atom', 'leaf', 'sigma', 'globe', 'book', 'dna', 'calc') then raise exception 'أيقونة غير متاحة' using errcode = '22023'; end if;
  if v_color not in ('teal', 'indigo', 'green', 'amber', 'rose', 'violet') then raise exception 'لون غير متاح' using errcode = '22023'; end if;
  begin v_sort := coalesce(nullif(p->>'sort', '')::int, 100); exception when others then raise exception 'الترتيب رقم صحيح' using errcode = '22023'; end;
  if v_sort not between 0 and 999 then raise exception 'الترتيب بين 0 و999' using errcode = '22023'; end if;
  if exists (select 1 from subjects where name = v_name and id <> v_id) then raise exception 'توجد مادة بهذا الاسم' using errcode = '22023'; end if;
  select to_jsonb(s) into v_before from subjects s where s.id = v_id;
  if v_mode = 'create' then
    if v_before is not null then raise exception 'رمز المادة مستخدم؛ اختر رمزًا آخر' using errcode = '22023'; end if;
    insert into subjects (id, name, icon, color, sort_order) values (v_id, v_name, v_icon, v_color, v_sort);
  else
    if v_before is null then raise exception 'المادة غير موجودة' using errcode = 'P0002'; end if;
    update subjects set name = v_name, icon = v_icon, color = v_color, sort_order = v_sort where id = v_id;
    update courses set subject = v_name where subject_id = v_id and subject is distinct from v_name;
  end if;
  select to_jsonb(s) into v_after from subjects s where s.id = v_id;
  perform public._log('subject', 0, case v_mode when 'create' then 'create' else 'edit' end, v_before, v_after, 'المادة: ' || v_name);
  return jsonb_build_object('id', v_id, 'name', v_name, 'icon', v_icon, 'color', v_color, 'sort', v_sort);
end $$;

-- إضافة مقرر في مادة: p = {subjectId, grade, term, code, title?, contentSource?}. يُنشأ «قيد الإعداد» دائمًا ولا يراه غير المالك.
create or replace function public.admin_save_course(p jsonb) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_subject text := trim(coalesce(p->>'subjectId', ''));
  v_grade text := trim(coalesce(p->>'grade', ''));
  v_term text := trim(coalesce(p->>'term', ''));
  v_code text := regexp_replace(trim(coalesce(p->>'code', '')), '\s+', ' ', 'g');
  v_title text := nullif(regexp_replace(trim(coalesce(p->>'title', '')), '\s+', ' ', 'g'), '');
  v_src text := nullif(trim(coalesce(p->>'contentSource', '')), '');
  v_name text; v_id bigint; v_gi int; v_ti int;
begin
  perform public._require_admin();
  select name into v_name from subjects where id = v_subject;
  if v_name is null then raise exception 'المادة غير موجودة' using errcode = '22023'; end if;
  v_gi := array_position(array['الأول الثانوي', 'الثاني الثانوي', 'الثالث الثانوي'], v_grade);
  v_ti := array_position(array['الأول', 'الثاني', 'الثالث'], v_term);
  if v_gi is null then raise exception 'الصف غير صالح' using errcode = '22023'; end if;
  if v_ti is null then raise exception 'الفصل الدراسي غير صالح' using errcode = '22023'; end if;
  if char_length(v_code) not between 2 and 40 then raise exception 'اسم المقرر بين 2 و40 حرفًا' using errcode = '22023'; end if;
  if v_title is not null and char_length(v_title) > 80 then raise exception 'العنوان طويل' using errcode = '22023'; end if;
  if v_src is not null and char_length(v_src) > 300 then raise exception 'مصدر المحتوى طويل (300 حرف كحد أقصى)' using errcode = '22023'; end if;
  if exists (select 1 from courses where kind = 'course' and subject_id = v_subject and grade = v_grade and term = v_term) then
    raise exception 'يوجد مقرر لهذه المادة في الصف والفصل نفسيهما' using errcode = '22023';
  end if;
  if exists (select 1 from courses where code = v_code) then raise exception 'يوجد مقرر بهذا الاسم؛ اختر اسمًا آخر' using errcode = '22023'; end if;
  insert into courses (code, title, subject, subject_id, grade, term, country, content_source, status, sort_order, kind)
    values (v_code, coalesce(v_title, v_code), v_name, v_subject, v_grade, v_term, 'السعودية', v_src, 'preparing', 100 + v_gi * 10 + v_ti, 'course')
    returning id into v_id;
  perform public._log('course', v_id, 'create', null,
    jsonb_build_object('id', v_id, 'code', v_code, 'subjectId', v_subject, 'grade', v_grade, 'term', v_term, 'status', 'preparing'), 'مقرر جديد: ' || v_code);
  return jsonb_build_object('id', v_id, 'code', v_code, 'subjectId', v_subject, 'grade', v_grade, 'term', v_term, 'status', 'preparing');
end $$;

-- إسناد معلم لمادة: add يسند له كل مقررات المادة الحالية، remove يلغي إسناد مقرراتها. يرجع عدد مقررات المادة المسندة له بعد التنفيذ.
-- (الإسناد يتوسع إلى صفوف teacher_courses؛ المقرر الذي يُضاف للمادة لاحقًا يُسند من جديد.)
create or replace function public.admin_assign_teacher_subject(p_teacher uuid, p_subject text, p_mode text default 'add') returns int
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_n int; v_name text;
begin
  perform public._require_admin();
  if p_mode not in ('add', 'remove') then raise exception 'إجراء غير صالح' using errcode = '22023'; end if;
  if not exists (select 1 from profiles where user_id = p_teacher and role = 'viewer') then raise exception 'الحساب ليس حساب معلم' using errcode = '22023'; end if;
  select name into v_name from subjects where id = p_subject;
  if v_name is null then raise exception 'المادة غير موجودة' using errcode = '22023'; end if;
  if p_mode = 'add' then
    insert into teacher_courses (teacher_id, course_id)
      select p_teacher, c.id from courses c where c.subject_id = p_subject and c.kind = 'course' on conflict do nothing;
  else
    delete from teacher_courses t using courses c where t.teacher_id = p_teacher and c.id = t.course_id and c.subject_id = p_subject;
  end if;
  select count(*) into v_n from teacher_courses t join courses c on c.id = t.course_id where t.teacher_id = p_teacher and c.subject_id = p_subject;
  perform public._log('teacher_subject', 0, p_mode, null, jsonb_build_object('teacher', p_teacher, 'subject', p_subject, 'courses', v_n),
    (case p_mode when 'add' then 'إسناد مادة ' else 'إلغاء إسناد مادة ' end) || v_name || ' للمعلم ' || coalesce((select display_name from profiles where user_id = p_teacher), ''));
  return v_n;
end $$;

-- معلمو المنصة مع مقرراتهم المسندة (لتبويب «المعلمون» في صفحة المادة)
create or replace function public.admin_list_teachers() returns jsonb
language plpgsql stable security definer set search_path = public, pg_temp as $$
begin
  perform public._require_admin();
  return (select coalesce(jsonb_agg(jsonb_build_object('id', pr.user_id, 'name', pr.display_name, 'username', split_part(u.email, '@', 1),
      'courses', (select coalesce(jsonb_agg(t.course_id order by t.course_id), '[]') from teacher_courses t where t.teacher_id = pr.user_id))
      order by pr.display_name), '[]')
    from profiles pr join auth.users u on u.id = pr.user_id where pr.role = 'viewer');
end $$;

-- إجماليات رئيسية المالك دون تكرار: الطالب المسند لأكثر من مادة يُعد مرة واحدة، وكذلك المعلم
create or replace function public.admin_platform_totals() returns jsonb
language plpgsql stable security definer set search_path = public, pg_temp as $$
begin
  perform public._require_admin();
  return jsonb_build_object(
    'students', (select count(distinct e.user_id) from course_enrollments e join profiles p on p.user_id = e.user_id and p.role = 'student'),
    'teachers', (select count(distinct t.teacher_id) from teacher_courses t join profiles p on p.user_id = t.teacher_id and p.role = 'viewer'));
end $$;

