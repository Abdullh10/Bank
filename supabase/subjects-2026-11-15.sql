create table if not exists public.subjects (
  id text primary key,
  name text not null,
  icon text,
  color text,
  sort_order int not null default 100,
  created_at timestamptz not null default now()
);
alter table public.subjects drop constraint if exists subjects_id_check;
alter table public.subjects add constraint subjects_id_check check (id ~ '^[a-z][a-z0-9-]{1,30}$');
create unique index if not exists subjects_name_key on public.subjects (name);
alter table public.subjects enable row level security;
revoke all on public.subjects from anon, authenticated;
